# The ring profiles are traced in proof-sheet pixels: height from crown, left and right silhouette.
CAST = {}
def species(name, col, row, floor, height, main):
    CAST[name] = dict(col=col,row=row,floor=floor,height=height,main=main,parts=[],lines=[],beads=[])
    return CAST[name]
def part(n,m,cy,depth,profile,cloth=False):
    data=[]
    for tok in profile.split():
        data.append(tuple(map(float,tok.split(','))))
    S['parts'].append((n,m,cy,depth,data,cloth))
def line(n,m,points,project=True):
    v=[tuple(map(float,p.split(','))) for p in points.split()]
    S['lines'].append((n,m,v,project))
def bead(n,m,x,z,d,rx,rz,rd,project=True):
    S['beads'].append((n,m,x,z,d,rx,rz,rd,project))
def limb(n,m,d,r,prof): part(n,m,d,r,prof, m in ('denim','khaki','brown','ink','canvas','rust','wine','blue','teal'))
def pairlegs(m,ds,left,right):
    limb('Left trouser leg',m,0,ds,left);limb('Right trouser leg',m,-3,ds,right)
def boots(m,ds,left,right):
    part('Left boot',m,5,ds,left);part('Right boot',m,4,ds,right)
def arms(m,ds,left,right):
    limb('Near arm',m,3,ds,left);limb('Far arm',m,-3,ds,right)
def body(n,m,d,r,prof):part(n,m,d,r,prof,True)
def head(m,d,r,prof):part('Cranium',m,d,r,prof)
def neck(m,d,r,prof):part('Neck',m,d,r,prof)
def eyes(m,positions):
    for i,(x,z,d,rx,rz) in enumerate(positions):bead('Eye globe '+str(i+1),m,x,z,d,rx,rz,rx*.64)
def hands(m,left,right):
    for side,pts in [('Near palm',left),('Far palm',right)]:
        if pts:
            x,z,d,w,h=pts;bead(side,m,x,z,d,w,h,w*.63)
def ring(n,m,x,z,d,rx,rz,rd,project=True):bead(n,m,x,z,d,rx,rz,rd,project)
